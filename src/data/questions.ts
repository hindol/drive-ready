const DRIVER_GUIDE_URL = 'https://www.dol.wa.gov/sites/default/files/documents/DriverGuide.pdf'

export const getReferenceLink = (reference: string): string | undefined => {
  if (!reference.startsWith('Washington Driver Guide')) {
    return undefined
  }
  const sectionPart = reference.split(',').slice(1).join(',').trim()
  if (!sectionPart) {
    return DRIVER_GUIDE_URL
  }
  const searchTerm = encodeURIComponent(sectionPart.replace(/\s+/g, ' '))
  return `${DRIVER_GUIDE_URL}#search=${searchTerm}`
}

